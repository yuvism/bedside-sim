/**
 * Builds docs/clinical-review.md: every content value flagged
 * "reviewNeeded": true, with its source, for a clinician to check.
 *
 *   npm run review:build
 *
 * A unit test fails when the committed file is out of date.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ROSC } from '../src/engine/als.ts';
import { COUPLING } from '../src/engine/coupling.ts';

export interface ContentFile {
  file: string;
  json: unknown;
}

interface Item {
  path: string;
  values: string;
  source: string;
}

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SKIP = new Set(['source', 'reviewNeeded']);

export function collectContentFiles(root: string = ROOT): ContentFile[] {
  const dir = join(root, 'src', 'content');
  const library = ['formulary.json', 'devices.json', 'investigations.json'].map((f) =>
    join(dir, f),
  );
  const cases = readdirSync(join(dir, 'cases'))
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => join(dir, 'cases', f));
  return [...library, ...cases].map((f) => ({
    file: relative(root, f).replace(/\\/g, '/'),
    json: JSON.parse(readFileSync(f, 'utf8')) as unknown,
  }));
}

const isObj = (x: unknown): x is Record<string, unknown> =>
  typeof x === 'object' && x !== null && !Array.isArray(x);

function labelOf(x: unknown, i: number): string {
  if (!isObj(x)) return String(i);
  for (const k of ['id', 'route', 'target']) if (typeof x[k] === 'string') return x[k];
  return String(i);
}

function summarise(node: Record<string, unknown>): string {
  const parts: string[] = [];
  for (const [k, v] of Object.entries(node)) {
    if (SKIP.has(k)) continue;
    if (typeof v === 'number' || typeof v === 'boolean') parts.push(`${k} ${v}`);
    else if (typeof v === 'string' && v.length <= 40) parts.push(`${k} ${v}`);
    else if (Array.isArray(v) && v.length && v.every((x) => isObj(x))) {
      parts.push(`${v.length} ${k} (see file)`);
    }
  }
  return parts.join('; ');
}

function walk(node: unknown, path: string, out: Item[]): void {
  if (Array.isArray(node)) {
    node.forEach((x, i) => walk(x, `${path}[${labelOf(x, i)}]`, out));
    return;
  }
  if (!isObj(node)) return;
  if (node['reviewNeeded'] === true) {
    const source = typeof node['source'] === 'string' ? node['source'] : '(no source)';
    out.push({ path: path || '(root)', values: summarise(node), source });
  }
  for (const [k, v] of Object.entries(node)) {
    if (typeof v === 'object' && v !== null) walk(v, path ? `${path}.${k}` : k, out);
  }
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

export function buildClinicalReview(files: readonly ContentFile[]): string {
  const sections: string[] = [];
  let total = 0;
  for (const f of files) {
    const items: Item[] = [];
    walk(f.json, '', items);
    if (!items.length) continue;
    total += items.length;
    const rows = items.map(
      (i) => `| \`${cell(i.path)}\` | ${cell(i.values)} | ${cell(i.source)} |`,
    );
    sections.push(
      [`## ${f.file}`, '', '| Item | Values | Source |', '| --- | --- | --- |', ...rows].join('\n'),
    );
  }
  const coupling = Object.entries(COUPLING).map(([k, v]) => `| \`${k}\` | ${v} |`);
  const rosc = Object.entries(ROSC).map(([k, v]) => `| \`${k}\` | ${v} |`);
  return [
    '# Clinical review list',
    '',
    'Generated by `npm run review:build` from the content files. Do not edit by hand.',
    '',
    'Each item below is a teaching parameter or an uncertain value marked `"reviewNeeded": true`.',
    'A clinician should check it against its source, then either confirm it (cite the guideline',
    'and remove the flag) or correct it.',
    '',
    `**${total} flagged items.**`,
    '',
    ...sections.flatMap((s) => [s, '']),
    '## Engine coupling constants',
    '',
    'Teaching parameters for the coupling model in `src/engine/coupling.ts` (baroreflex, oxygen',
    'delivery, consciousness, lactate, urine output). None are taken from a guideline.',
    '',
    '| Constant | Value |',
    '| --- | --- |',
    ...coupling,
    '',
    '## ROSC model constants',
    '',
    'Teaching parameters for the chance of return of spontaneous circulation in `src/engine/als.ts`.',
    'Shock and pulse-check odds rise with CPR fraction, early action, fixing the cause and ALS drugs.',
    '',
    '| Constant | Value |',
    '| --- | --- |',
    ...rosc,
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const md = buildClinicalReview(collectContentFiles());
  writeFileSync(join(ROOT, 'docs', 'clinical-review.md'), md);
  console.log('Wrote docs/clinical-review.md');
}

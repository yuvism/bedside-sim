/**
 * Keeps the Unity port pack in step with the web app:
 *   - copies the content JSON into unity/Assets/StreamingAssets/BedsideSim/
 *   - generates the parity fixtures the C# engine is checked against
 *
 *   npm run unity:sync
 *
 * A unit test fails when the copies or fixtures are out of date.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  DeviceTableSchema,
  FormularySchema,
  InvestigationTableSchema,
} from '../src/content/librarySchema.ts';
import { CaseSchema } from '../src/content/schema.ts';
import { SimpleEngine } from '../src/engine/engine.ts';
import { runScript, type ScriptStep } from '../src/engine/replay.ts';
import type { CaseDef, EngineLibrary, SimEvent } from '../src/engine/types.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const UNITY_DATA = join('unity', 'Assets', 'StreamingAssets', 'BedsideSim');
const LIBRARY_FILES = ['formulary.json', 'devices.json', 'investigations.json', 'team.json'];

export interface OutFile {
  /** Path relative to the repo root, forward slashes. */
  path: string;
  text: string;
}

/** Content files copied byte for byte. */
export function contentCopies(root: string = ROOT): OutFile[] {
  const src = join(root, 'src', 'content');
  const cases = readdirSync(join(src, 'cases'))
    .filter((f) => f.endsWith('.json'))
    .sort();
  return [
    ...LIBRARY_FILES.map((f) => ({ from: join(src, f), to: `${UNITY_DATA}/${f}` })),
    ...cases.map((f) => ({ from: join(src, 'cases', f), to: `${UNITY_DATA}/cases/${f}` })),
  ].map(({ from, to }) => ({ path: to.replace(/\\/g, '/'), text: readFileSync(from, 'utf8') }));
}

type Row = [number, ...(number | null)[], string];

interface Scenario {
  name: string;
  description: string;
  script: ScriptStep[];
  maxSec: number;
  stopOnOutcome: boolean;
  sampleEverySec: number;
}

/** The anaphylaxis ideal-run script (same as tests/unit/cases/policies.ts). */
export const ANAPHYLAXIS_IDEAL: ScriptStep[] = [
  { t: 5, action: { kind: 'call_help' } },
  { t: 10, action: { kind: 'talk', questionId: 'allergy' } },
  ...['A', 'B', 'C', 'D', 'E'].map((examId, i) => ({
    t: 15 + i * 3,
    action: { kind: 'exam' as const, examId },
  })),
  { t: 45, action: { kind: 'device', deviceId: 'o2_nrb', on: true } },
  { t: 60, action: { kind: 'drug', drugId: 'adrenaline', route: 'IM', dose: 0.5 } },
  { t: 70, action: { kind: 'procedure', procedureId: 'iv_access' } },
  { t: 80, action: { kind: 'fluid', fluidId: 'crystalloid', volumeMl: 500 } },
  { t: 90, action: { kind: 'diagnosis', diagnosisId: 'anaphylaxis' } },
  { t: 360, action: { kind: 'drug', drugId: 'adrenaline', route: 'IM', dose: 0.5 } },
];

const SCENARIOS: Scenario[] = [
  {
    name: 'ideal',
    description: 'Ideal run: help, O2, IM adrenaline at 1:00 and 6:00, IV access, fluids.',
    script: ANAPHYLAXIS_IDEAL,
    maxSec: 1800,
    stopOnOutcome: true,
    sampleEverySec: 1,
  },
  {
    name: 'untreated',
    description: 'No treatment: PEA arrest, then death after 15 minutes without ROSC.',
    script: [],
    maxSec: 3600,
    stopOnOutcome: true,
    sampleEverySec: 5,
  },
];

const VITAL_COLS = ['hr', 'sbp', 'dbp', 'map', 'spo2', 'rr', 'etco2', 'temp', 'gcs'] as const;

function runScenario(lib: EngineLibrary, c: CaseDef, seed: number, sc: Scenario) {
  const trace: Row[] = [];
  const sample = (e: SimpleEngine) => {
    if (e.time % sc.sampleEverySec !== 0) return;
    const v = e.vitals();
    trace.push([e.time, ...VITAL_COLS.map((k) => v[k]), v.rhythm]);
  };
  const first = new SimpleEngine(lib);
  first.load(c, seed);
  sample(first);
  const r = runScript(lib, c, seed, sc.script, {
    maxSec: sc.maxSec,
    stopOnOutcome: sc.stopOnOutcome,
    onTick: sample,
  });
  return {
    name: sc.name,
    description: sc.description,
    script: sc.script,
    maxSec: sc.maxSec,
    stopOnOutcome: sc.stopOnOutcome,
    sampleEverySec: sc.sampleEverySec,
    outcome: r.outcome,
    endT: r.endT,
    events: r.events.map((e: SimEvent) => ({ t: e.t, type: e.type, code: e.code, text: e.text })),
    columns: ['t', ...VITAL_COLS, 'rhythm'],
    trace,
  };
}

export function parityFixture(lib: EngineLibrary, c: CaseDef, seed = 1): OutFile {
  const fixture = {
    format: 'bedside-sim-parity',
    formatVersion: 1,
    note: 'Generated by npm run unity:sync from the TypeScript engine. Do not edit by hand.',
    caseId: c.id,
    caseVersion: c.version,
    seed,
    tolerance: 1e-6,
    scenarios: SCENARIOS.map((sc) => runScenario(lib, c, seed, sc)),
  };
  return {
    path: `${UNITY_DATA}/parity/${c.id}.json`,
    text: `${JSON.stringify(fixture, null, 1)}\n`,
  };
}

export function writeAll(files: readonly OutFile[], root: string = ROOT): void {
  for (const f of files) {
    const abs = join(root, f.path);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, f.text);
  }
}

/** Library and case parsed with the content schemas (no Vite needed). */
export function loadFromDisk(root: string = ROOT): { lib: EngineLibrary; ana: CaseDef } {
  const read = (p: string) => JSON.parse(readFileSync(join(root, p), 'utf8')) as unknown;
  const lib: EngineLibrary = {
    formulary: FormularySchema.parse(read('src/content/formulary.json')),
    devices: DeviceTableSchema.parse(read('src/content/devices.json')),
    investigations: InvestigationTableSchema.parse(read('src/content/investigations.json')),
  };
  const ana = CaseSchema.parse(read('src/content/cases/anaphylaxis-01.json'));
  return { lib, ana };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { lib, ana } = loadFromDisk();
  const files = [...contentCopies(), parityFixture(lib, ana)];
  writeAll(files);
  console.log(`Wrote ${files.length} files under ${UNITY_DATA}`);
}
